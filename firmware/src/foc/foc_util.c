#include "foc_util.h"

/* Приведение угла к [-pi, pi).
 *
 * Реализация намеренно без цикла: два условия, время выполнения ограничено
 * сверху константой. Предусловие |angle| < 3*pi выполняется всегда, потому
 * что угол накапливается шагами меньше 2*pi за период управления.
 *
 * Вариант с while был бы формально универсальнее, но нарушал бы правило
 * "никаких операций с неограниченным временем в обработчике прерывания":
 * при повреждённом входе он зациклился бы намертво вместе с ШИМ.
 */
float foc_wrap_pi(float angle)
{
    if (angle >= FOC_PI) {
        angle -= FOC_2PI;
    }
    if (angle < -FOC_PI) {
        angle += FOC_2PI;
    }
    return angle;
}

float foc_clampf(float x, float lo, float hi)
{
    if (x < lo) {
        return lo;
    }
    if (x > hi) {
        return hi;
    }
    return x;
}

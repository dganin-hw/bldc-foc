#include "motor_params.h"
#include "foc_util.h"

float motor_lambda_from_kv(float kv, int pole_pairs)
{
    return 60.0f / (FOC_2PI * kv * (float)pole_pairs);
}

/* --------------------------------------------------------------------------
 * GBM2804H-100T - мотор разработки.
 *
 * ИЗМЕРЕНО:      пока ничего, все числа оценочные.
 * ОЦЕНКА:        R и L - типовые для gimbal-мотора на 100 витков.
 * ТРЕБУЕТ ЗАМЕРА: всё, на этапе 2.
 *
 * Важно: коэффициенты токового контура зависят только от R и L
 *     Kp = wc * L,  Ki = wc * R
 * и от lambda_m не зависят вообще. Поэтому токовый контур можно настраивать
 * с неизмеренным lambda_m: он влияет только на обратную ЭДС и масштаб
 * момента, то есть на контур скорости.
 *
 * kV взят 100 об/мин на вольт как разумная середина для этого класса.
 * Разброс у продавцов большой, реальное значение может отличаться в разы -
 * поэтому число помечено как оценка, а не как параметр.
 *
 * Как измерить на этапе 2:
 *   R  - миллиомметром между двумя фазами, поделить пополам
 *   L  - LCR-метром между двумя фазами на 1 кГц, поделить пополам
 *   kV - раскрутить мотор дрелью на известных оборотах, снять осциллографом
 *        амплитуду напряжения между фазами на холостом ходу
 * -------------------------------------------------------------------------- */
const motor_params_t MOTOR_GBM2804H_100T = {
    .name       = "GBM2804H-100T",
    .pole_pairs = 7,
    .r_phase    = 11.0f,      /* ОЦЕНКА */
    .l_phase    = 4.0e-3f,    /* ОЦЕНКА */
    .lambda_m   = 0.0136418f, /* ОЦЕНКА: 60 / (2*pi * 100 * 7) */
    .kv         = 100.0f,     /* ОЦЕНКА */
    .i_max      = 1.0f,       /* при 12 В и 11 Ом больше просто не получится */
    .j_rotor    = 1.0e-6f,    /* ОЦЕНКА */
    .b_visc     = 1.0e-6f,    /* ОЦЕНКА */
};


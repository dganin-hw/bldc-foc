#ifndef FOC_CONFIG_H
#define FOC_CONFIG_H

/* Тактирование и ШИМ.
 *
 * Значения совпадают с зафиксированной конфигурацией CubeMX,
 * см. docs/pin-plan.md и hardware/dev-board/cubemx/CubeMX.ioc.
 * Менять только вместе с ней.
 */

#define FOC_TIM_CLK_HZ    170000000.0f  /* APB2 timer clock */
#define FOC_PWM_FREQ_HZ   48000.0f
#define FOC_TIM_ARR       1770          /* центрированный счёт: f = clk/(2*ARR) */

/* Период управления: один шаг FOC на каждый период ШИМ. */
#define FOC_TS            (1.0f / FOC_PWM_FREQ_HZ)   /* 20.833 мкс */

/* Ограничение скважности.
 *
 * Снизу - чтобы нижний ключ успевал побыть открытым достаточно долго для
 * измерения тока через шунт: нужно время установления плюс выборка АЦП.
 * Сверху - чтобы успевал заряжаться bootstrap-конденсатор верхнего плеча.
 *
 * Уточнить по осциллографу на этапе 2.
 */
#define FOC_DUTY_MIN      0.03f
#define FOC_DUTY_MAX      0.97f

/* Напряжение шины по умолчанию для симулятора и первых включений.
 * На железе берётся с делителя через ADC1_IN3 (PA2). */
#define FOC_VDC_NOMINAL   12.0f

/* Компенсация запаздывания угла: ток измерен в момент t, а вычисленное
 * напряжение начнёт действовать в среднем через 1.5 периода. На высокой
 * электрической частоте поправка достигает десятков градусов, см. §13
 * docs/foc-theory.md. */
#define FOC_ANGLE_DELAY_PERIODS  1.5f

#endif /* FOC_CONFIG_H */
